CREATE TABLE `app_analytics_events` (
  `id` VARCHAR(36) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `companyId` VARCHAR(191) NOT NULL,
  `sessionId` VARCHAR(36) NOT NULL,
  `module` VARCHAR(32) NOT NULL,
  `screen` VARCHAR(80) NOT NULL,
  `flow` VARCHAR(80) NULL,
  `interactionId` VARCHAR(36) NULL,
  `action` VARCHAR(32) NOT NULL,
  `platform` VARCHAR(12) NOT NULL,
  `appVersion` VARCHAR(40) NOT NULL,
  `releaseId` VARCHAR(40) NOT NULL,
  `environment` VARCHAR(16) NOT NULL,
  `tutorial` BOOLEAN NOT NULL DEFAULT false,
  `durationMs` INTEGER NULL,
  `statusCode` INTEGER NULL,
  `occurredAt` DATETIME(3) NOT NULL,
  `receivedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `AppAnalyticsEvent_occurredAt_idx` (`occurredAt`),
  INDEX `AppAnalyticsEvent_companyId_occurredAt_idx` (`companyId`, `occurredAt`),
  INDEX `AppAnalyticsEvent_sessionId_module_occurredAt_idx` (`sessionId`, `module`, `occurredAt`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
